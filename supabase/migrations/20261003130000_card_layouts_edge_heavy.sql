-- Веха M7, шаг B7.7 (решение Q-1, 2026-10-03): тяжёлые макеты вне подбора до переезда сборки.
--
-- Часть макетов библиотеки не успевает собраться в Edge Function в размере профиля площадки:
-- супервизор рантайма снимает запрос (`503` или `546`) и убивает изолят (замер B4.0, ADR-0015).
-- Пока сборка не переехала на коробку, такие макеты не должны попадать ни в платную
-- карточку, ни в превью. Признак живёт столбцом, а не списком в коде: так решение видно в
-- дифе миграции и снимается одной миграцией, когда сборка переедет.
--
-- Универсальный макет тяжёлым быть не может: он последний рубеж подбора, и если бы он тоже
-- падал, на пустом совпадении платный прогон не имел бы безопасного ответа.

alter table public.card_layouts
  add column edge_heavy boolean not null default false;

alter table public.card_layouts
  add constraint card_layouts_fallback_not_heavy
  check (not (is_fallback and edge_heavy));

comment on column public.card_layouts.edge_heavy is
  'Макет не успевает собраться в Edge Function в размере профиля; подбор его не выдаёт, пока сборка не переехала на коробку (ADR-0015, решение Q-1).';
