-- FR-19: стартовые баллы за подтверждение email — 300 вместо 120.
--
-- N = 300 — владелец 2026-10-05 (planning/reference/UNIT_ECONOMICS.md §8). Причина: карточка
-- с сочинением стоит 130 баллов (CARD_SURCHARGE = 80), и со 120 новый продавец не мог её
-- купить. С 300 он берёт две карточки или карточку и фотогенерации.
--
-- Начисление НЕ задним числом: уже зачисленные бонусы остаются как есть. Заменяется только
-- число в триггерной функции, а она срабатывает на подтверждении, которого у прежних
-- аккаунтов больше не будет. Разовую догонку из 20260828130000 не повторяем — она нужна
-- была аккаунтам, подтверждённым до самой миграции; а ключ `signup:<sha256>` не даст
-- второго начисления тому, кто уже получил свои 120 (NFR-03, ADR-0009).
--
-- Остальное тело функции — как в 20260828130000_signup_bonus.sql; триггеры её вызывают по
-- имени, пересоздавать их не надо.
create or replace function app.grant_signup_bonus()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- Адрес может отсутствовать (вход по телефону выключен, но выключается он настройкой,
  -- а не схемой). Без адреса ключа не построить — и начислять не за что.
  if new.email is null then
    return new;
  end if;

  -- N = 300 — владелец 2026-10-05, UNIT_ECONOMICS.md §8. Число живёт здесь одно: клиент
  -- показывает фактический баланс, а не свою копию номинала.
  perform public.apply_credit_operation(
    new.id, 300, 'signup_bonus', app.signup_bonus_key(new.email)
  );

  return new;
end;
$$;

comment on function app.grant_signup_bonus() is
  'Начисляет стартовые баллы в транзакции подтверждения email (FR-19), N = 300. Ошибку не глотает: потерянное начисление обнаружится только в претензии, упавшее подтверждение — сразу.';
