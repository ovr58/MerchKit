-- Веха M7, шаг B2: универсальный макет в библиотеке обязан быть один.
--
-- Подбор обещает не падать на пустом совпадении и быть воспроизводимым. Два универсальных
-- макета ломают второе обещание молча: какой из них вернётся, зависит от порядка строк, а его
-- база не гарантирует. Ограничение дешевле, чем сортировка на каждом чтении.

create unique index card_layouts_single_fallback
  on public.card_layouts (is_fallback)
  where is_fallback;

comment on index public.card_layouts_single_fallback is
  'Универсальный макет ровно один: подбор на пустом совпадении обязан возвращать один и тот же макет.';
