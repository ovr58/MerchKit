/**
 * Язык макета карточки — шаг A1 плана
 * [`card-assembly-pipeline_2026-08-31.md`](../../../../planning/active/card-assembly-pipeline_2026-08-31.md).
 *
 * **Макет — это данные, а не картинка и не промпт.** Модель изображений рисует сцену;
 * заголовок, характеристики, плашки и логотип ставит наша программа по этому описанию
 * ([ADR-0012](../../../../docs/adr/0012-card-layout-is-ours-not-vendors.md)). Отсюда два
 * свойства, которых у прежней схемы не было: текст выходит ровно тот, что задан, а повторная
 * сборка ничего не стоит.
 *
 * **Геометрия — в долях холста, а не в пикселях.** Один и тот же макет собирается под кадр
 * любой площадки (FR-25): пиксели приходят из `OutputProfile` в момент сборки. Пиксели в
 * макете означали бы отдельный макет на каждую пару «маркетплейс × категория» — 21 копию
 * одного и того же.
 *
 * **Словари закрытые.** Тип слоя, режим наложения, эффект, роль шрифта — перечисления, а не
 * свободные строки. Причина не в аккуратности: макеты придёт сочинять модель (шаг A4 —
 * разбор образца, шаг B5 — арт-директор), и всё, чего нет в словаре, она сочинит. Закрытый
 * словарь превращает «сборщик не умеет такой эффект» из брака в кадре в отказ валидатора до
 * рендера.
 *
 * **Число и порядок слоёв не фиксированы** (решение пользователя 2026-08-31). Логотип может
 * лежать и перед моделью, и за ней — поэтому z-порядок хранится полем, а не подразумевается
 * жёстким шаблоном.
 *
 * Правило отсутствующего ассета (K-3) живёт в `validate.ts`, а не здесь: это поведение
 * сборки, а не форма записи.
 */

/** Доля стороны холста: 0 — левый (верхний) край, 1 — правый (нижний). Значения вне [0, 1]
 *  законны — так задаётся вылет за обрез, например слово-подложка, уходящее за правый край. */
export type Fraction = number

/** Прямоугольник в долях. У вложенного слоя — доли бокса группы, а не холста. */
export type Box = { x: Fraction; y: Fraction; w: Fraction; h: Fraction }

/** Точка интереса кадра в долях самого кадра: что не должно уйти под обрез при `cover`. */
export type Focus = { x: Fraction; y: Fraction }

export const LAYER_TYPES = ['frame', 'cutout', 'shape', 'asset', 'text', 'group'] as const
export type LayerType = (typeof LAYER_TYPES)[number]

/** Наложение. Три режима, а не пятнадцать из CSS: больше сборщик не умеет, а чего он не
 *  умеет — того нет в словаре. */
export const BLEND_MODES = ['normal', 'multiply', 'screen'] as const
export type BlendMode = (typeof BLEND_MODES)[number]

/** Роль шрифта, а не гарнитура (шаг A4): по растру образца гарнитуру достоверно не
 *  восстановить и чаще всего не лицензировать. Роль отображается в конкретный файл базой
 *  шрифтов на стороне сборщика. */
export const FONT_ROLES = ['display', 'heading', 'body', 'label', 'accent'] as const
export type FontRole = (typeof FONT_ROLES)[number]

/** Текстовые гнёзда карточки. Характеристики товара сюда не входят — у них своя привязка
 *  `prop`, потому что их число переменное. */
export const TEXT_SLOTS = ['title', 'subtitle', 'kicker', 'body', 'sizes', 'brand'] as const
export type TextSlot = (typeof TEXT_SLOTS)[number]

export const TEXT_ALIGNS = ['left', 'center', 'right'] as const
export type TextAlign = (typeof TEXT_ALIGNS)[number]

export const TEXT_VALIGNS = ['top', 'middle', 'bottom'] as const
export type TextValign = (typeof TEXT_VALIGNS)[number]

export const TEXT_TRANSFORMS = ['none', 'upper'] as const
export type TextTransform = (typeof TEXT_TRANSFORMS)[number]

export const FIT_MODES = ['cover', 'contain'] as const
export type FitMode = (typeof FIT_MODES)[number]

/** Точка градиента. */
export type PaintStop = { at: Fraction; color: string; opacity?: number }

/**
 * Заливка. Градиент — не украшение: им задаётся тёмная подложка под текстовой колонкой, без
 * которой белый заголовок на светлом фоне нечитаем.
 *
 * **`radial` добавлен 2026-08-31 по итогам гейта A3.** На образце «платье» белая плашка
 * размеров не залита ровным белым: она светлее в середине и гаснет к углам — фотографическое
 * падение к краям. Линейным градиентом это не записывается, а без него плашка выглядит
 * наклейкой. Ровно тот случай, ради которого гейт и стоит перед набором библиотеки: словарь
 * расширяется по найденной нехватке, а не «на будущее».
 */
export type Paint =
  | { kind: 'solid'; color: string; opacity?: number }
  | {
      kind: 'linear'
      /** Начало и конец градиента в долях бокса слоя. */
      from: Focus
      to: Focus
      stops: PaintStop[]
    }
  | {
      kind: 'radial'
      /** Центр в долях бокса слоя. */
      center: Focus
      /** Радиус долей бокса: 0.5 — до края по горизонтали. Пятно тянется вместе с боксом, а
       *  не остаётся круглым, — падение к краям обязано повторять форму плашки. */
      radius: Fraction
      stops: PaintStop[]
    }

export type ShapeForm =
  | { form: 'rect'; radius?: Fraction }
  | { form: 'ellipse' }
  | { form: 'line'; thickness: Fraction }

export const EFFECT_KINDS = ['shadow', 'blur', 'stroke'] as const
export type EffectKind = (typeof EFFECT_KINDS)[number]

/**
 * Смещения, радиусы и толщины эффектов — тоже в долях холста: эффект обязан масштабироваться
 * вместе с макетом, иначе тень, выверенная на 1200 px, на 2400 px станет вдвое тоньше.
 *
 * **`stroke` вернулся 2026-08-31 по итогам гейта A3.** Он был убран из словаря как то, чего
 * не требовал ни один разобранный образец, — и это оказалось ошибкой разбора, а не верным
 * YAGNI: на образце «куртка» у плашек светлая волосяная обводка, и оранжевый кружок «+»
 * посажен ровно на неё. Без обводки плашка теряет край и кружку не на чем стоять.
 */
export type Effect =
  | { kind: 'shadow'; dx: Fraction; dy: Fraction; blur: Fraction; color: string; opacity: number }
  | { kind: 'blur'; radius: Fraction }
  | { kind: 'stroke'; color: string; thickness: Fraction; opacity?: number }

/**
 * Чем слой наполняется. Нет привязки — слой декоративный, его содержимое записано прямо в
 * макете (рамка, разделитель, слово-подложка).
 *
 * Привязка — единственный способ для слоя сослаться на содержимое, и именно она делает
 * исполнимым правило K-3: сборщик знает, чего именно не хватило, и снимает ровно этот слой.
 */
export type Binding =
  /** Кадр вендора. Индекс не задан — первый: карточка с одним снимком пишется как раньше.
   *  Индексы появились 2026-08-31 — на образце с детальным снимком товара второй кадр было
   *  нечем адресовать, и в угол уезжала вся карточка целиком вместо детали. */
  | { kind: 'frame'; index?: number }
  | { kind: 'cutout' }
  | { kind: 'logo' }
  | { kind: 'text'; slot: TextSlot }
  /** Характеристика товара (шаг B1). `part` не задан — привязан весь модуль целиком:
   *  нет характеристики → группа не рисуется. */
  | { kind: 'prop'; index: number; part?: 'label' | 'value' | 'icon' }
  | { kind: 'swatch'; index: number }

/**
 * Прогон внутри строки: кусок текста, отличающийся от стиля слоя начертанием, кеглем или
 * цветом.
 *
 * **Заведён 2026-08-31 по разбросу A6.** Три образца из шести набирают одну фразу двумя
 * начертаниями («Dual SIM», «СИЗ по ГОСТ», «16/1024 гб»). Раньше это приходилось разбивать на
 * два слоя — привязанный и декоративный, — и получалась не косметическая, а ломающая ошибка:
 * привязка снимала только свою половину, а статический хвост оставался висеть в кадре над
 * пустым местом. Прогоны держат фразу одним слоем, поэтому K-3 уносит её целиком.
 */
export type TextRun = {
  /** Не задан — в этот прогон подставляется содержимое привязки слоя. Такой прогон один. */
  text?: string
  weight?: number
  size?: Fraction
  color?: string
}

/** Строка макета: цельная или составленная из прогонов разного начертания. */
export type TextLine = string | TextRun[]

export type TextStyle = {
  role: FontRole
  /** Кегль долей ВЫСОТЫ холста. Высотой, а не шириной: при смене профиля площадки меняется
   *  прежде всего высота кадра, и текст должен ехать вместе с ней. */
  size: Fraction
  weight: number
  italic?: boolean
  color: string
  align: TextAlign
  valign: TextValign
  /** Множитель к кеглю. */
  lineHeight: number
  /** Межбуквенный интервал долей кегля. */
  tracking?: number
  transform?: TextTransform
}

type LayerBase = {
  id: string
  /** Порядок отрисовки: больше — ближе к зрителю. Хранится числом, а не позицией в массиве,
   *  потому что арт-директор (шаг B5) вставляет слои между существующими, а не в конец. */
  z: number
  box: Box
  opacity?: number
  blend?: BlendMode
  effects?: Effect[]
  bind?: Binding
  /**
   * Поворот в градусах вокруг центра бокса; положительный — по часовой стрелке.
   *
   * **Заведён 2026-08-31 по разбросу A6.** Вертикальные надписи встретились на трёх образцах
   * из шести (название смартфона в узкой колонке, водяной знак по краю кадра, стрелка-указатель).
   * Без поворота разбор был вынужден класть их горизонтально, и на смартфоне это разрывало
   * колонку — сборка выходила не неточной, а неверной.
   */
  rotate?: number
}

/**
 * Скругление углов слоя-картинки долей МЕНЬШЕЙ стороны бокса: круг из квадрата получается при
 * 0.5, и та же запись даёт одинаковый радиус на кадре любой пропорции.
 *
 * **Заведено 2026-08-31 по разбросу A6.** Скруглённые углы нашлись на трёх образцах из шести
 * (голубая рамка шин, подложка смартфона, фотовставка в бейдже обуви). У `shape` радиус был
 * с самого начала, у слоёв с картинкой — нет, и на шинах это оказалось единственным видимым
 * расхождением с оригиналом.
 */
type Rounded = { radius?: Fraction }

/** Кадр вендора целиком. */
export type FrameLayer = LayerBase & Rounded & { type: 'frame'; fit: FitMode; focus?: Focus }

/** Вырез товара из того же кадра (K-2): нужен, только когда текст должен уходить за товар. */
export type CutoutLayer = LayerBase & Rounded & { type: 'cutout'; fit: FitMode; focus?: Focus }

export type ShapeLayer = LayerBase & { type: 'shape'; shape: ShapeForm; fill?: Paint }

/**
 * Картинка из базы: логотип, иконка, образец цвета.
 *
 * **`ink` — краска иконки, заведена 2026-09-01 (шаг A8).** База иконок общая и макету не
 * принадлежит: один и тот же градусник ложится и под «температуру носки» куртки, и под
 * «температуру хранения» БАДа. Значит цвет — не свойство файла, а параметр сборки. Исходник
 * иконки рисуется одной краской (`currentColor` и в `stroke`, и в `fill`), а конкретный цвет
 * приходит отсюда.
 *
 * Выбирает его макет, а не сборщик: по [ADR-0012](../../../../docs/adr/0012-card-layout-is-ours-not-vendors.md)
 * сборщик исполняет и художественных решений не принимает, а чтобы подобрать цвет по контрасту,
 * ему пришлось бы знать, что под иконкой — плашка, градиент или фотография. Арт-директор (шаг
 * B5) знает это бесплатно: плашку положил он сам.
 *
 * Не задана — иконка рисуется тёмной по умолчанию: на белом читается, а на тёмной плашке
 * валидатор поймает контрастом.
 */
export type AssetLayer = LayerBase & Rounded & { type: 'asset'; fit: FitMode; ink?: string }

/** Разбиение на строки задаётся макетом, а не подбирается сборщиком: перенос — решение
 *  вёрстки («КУРТКА» и «МУЖСКАЯ» — две строки разного кегля, а не одна фраза). */
export type TextLayer = LayerBase & { type: 'text'; style: TextStyle; lines?: TextLine[] }

/** Модуль: иконка + подпись + плашка, которые появляются и исчезают вместе. */
export type GroupLayer = LayerBase & { type: 'group'; children: Layer[] }

export type Layer =
  | FrameLayer
  | CutoutLayer
  | ShapeLayer
  | AssetLayer
  | TextLayer
  | GroupLayer

export type LayoutCanvas = {
  /** Пропорция, под которую макет нарисован. Пиксели приходят из `OutputProfile`. */
  aspectW: number
  aspectH: number
  background: Paint
}

export type CardLayout = {
  id: string
  title: string
  canvas: LayoutCanvas
  layers: Layer[]
}

/** Картинка, готовая лечь в композицию: data-URI, потому что сборка обязана быть
 *  самодостаточной — внешних загрузок во время рендера нет. */
export type ImageRef = { dataUri: string; width: number; height: number }

/** Характеристика товара из шага B1. Любое поле может отсутствовать — это штатный случай,
 *  а не ошибка (решение 4 от 2026-08-31). */
export type CardProp = { label?: string; value?: string; icon?: ImageRef }

/** Чем наполняется макет на конкретной сборке. */
export type CardContent = {
  /** Кадры вендора по порядку: первый — основная сцена, дальше детальные снимки. */
  frames?: ImageRef[]
  cutout?: ImageRef
  logo?: ImageRef
  texts: Partial<Record<TextSlot, string[]>>
  props: CardProp[]
  swatches: (ImageRef | { color: string })[]
}
