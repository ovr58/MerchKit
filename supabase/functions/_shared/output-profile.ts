/**
 * Соответствие готового файла требованиям площадки (FR-25).
 *
 * **Правило живёт в одном файле, потому что применяют его двое.** Провайдер проверяет свой
 * же выход, чтобы упасть сразу и с внятной диагностикой, а `generation-worker` — потому что
 * верить провайдеру на слово нельзя: файл не по требованиям площадки это файл, за который
 * пользователь заплатил зря. Две копии одного правила разъезжаются — ровно эту ошибку
 * `pricing.ts` обходит одним файлом на клиента и сервер.
 *
 * **Почему не равенство размеров.** До M5 проверка требовала точного `width` × `height`, и
 * на живом вендоре это отвергало **каждую** генерацию: модели изображений принимают не
 * пиксели, а бакеты разрешения, и произвольный размер им недоступен (миграция
 * 20260829140000). Сами площадки формулируют требование как порог, а не как равенство:
 * «минимум 700 × 900», «не меньше 300 × 300». Проверяем так же, как требуют они.
 *
 * Соотношение сторон при этом сверяется, и с малым допуском: перевернуть вертикальный кадр
 * в горизонтальный или обрезать 3 : 4 до квадрата площадка не простит, а бакет вендора даёт
 * доли процента расхождения (896 × 1200 против ровных 3 : 4 — 0,44%).
 */

import { readImageInfo } from './image.ts'
import type { OutputProfile } from './ai-provider/types.ts'

/** Допуск по соотношению сторон. 2% покрывает округление бакетов вендора и заведомо не
 *  пропускает смену ориентации или подмену пропорции. */
const ASPECT_TOLERANCE = 0.02

/**
 * Возвращает описание несоответствия или `null`, если файл площадке подходит.
 *
 * Строка предназначена нашим логам и `failure_reason`, а не пользователю: наружу US-E4
 * показывает возврат баллов, а не устройство вендора.
 */
export function describeProfileMismatch(bytes: Uint8Array, profile: OutputProfile): string | null {
  const info = readImageInfo(bytes)

  if (info === null) {
    return 'формат готового файла не распознан'
  }

  if (!profile.formats.includes(info.format)) {
    return `формат ${info.format} не принимается площадкой ${profile.marketplaceTitle} ` +
      `(принимаются: ${profile.formats.join(', ')})`
  }

  if (info.width < profile.minWidth || info.height < profile.minHeight) {
    return `размер ${info.width} × ${info.height} ниже порога площадки ` +
      `${profile.minWidth} × ${profile.minHeight}`
  }

  // Сверяемся с объявленным соотношением площадки, а не с частным от целевых пикселей:
  // целевой кадр подобран под бакет вендора и сам отклоняется от ровного отношения.
  const wanted = profile.aspectW / profile.aspectH
  const got = info.width / info.height

  if (Math.abs(got - wanted) / wanted > ASPECT_TOLERANCE) {
    return `соотношение сторон ${info.width} × ${info.height} не совпадает с профилем ` +
      `${profile.aspectLabel}`
  }

  if (bytes.length > profile.maxBytes) {
    return `файл ${(bytes.length / 1048576).toFixed(1)} МБ превышает предел площадки ` +
      `${(profile.maxBytes / 1048576).toFixed(0)} МБ`
  }

  return null
}
