/**
 * Пределы и проверка логотипа продавца (шаг B3 плана
 * [`card-assembly-pipeline_2026-08-31.md`](../../../planning/active/card-assembly-pipeline_2026-08-31.md)).
 *
 * **Лежит рядом с `uploads.ts` и по той же причине:** отказ обязан звучать одинаково у
 * клиента и у сервера. Клиент проверяет файл до отправки, чтобы человек узнал о проблеме
 * сразу; `generate` перепроверяет те же байты последним рубежом — интерфейс можно обойти,
 * а в кадр логотип попадёт уже за деньги.
 *
 * **Почему проверка строгая, хотя логотип необязателен.** Отсутствие логотипа — штатный
 * случай: слой снимается правилом K-3, карточка собирается без него. А вот принятый, но
 * негодный файл ломает ровно то, ради чего логотип и грузят: белый прямоугольник поверх
 * фотографии вместо знака или мыло вместо букв. Не загрузить лучше, чем загрузить плохо.
 *
 * **Прозрачность проверяется по заголовку, а не по пикселям.** В PNG наличие альфа-канала
 * записано в IHDR, а «цветной ключ» и палитровая прозрачность — чанком `tRNS`; и то и
 * другое читается из первых байтов. Убедиться, что прозрачные пиксели там ЕСТЬ, значило бы
 * распаковать IDAT — и ради чего: господствующий случай («сохранил знак на белом фоне»)
 * альфа-канала не имеет вовсе и отсекается заголовком.
 */

import { readImageInfo } from './image.ts'

/** Только PNG: JPEG прозрачности не умеет в принципе, а SVG в кадр не кладём — сборщик
 *  растеризует свой SVG сам, и чужая разметка внутри него это чужой код в нашем документе. */
export const LOGO_MIME = 'image/png'

/**
 * 2 МБ. Знак — это несколько плашек цвета, а не фотография: PNG 1000×1000 с прозрачностью
 * весит сотни килобайт. Всё, что больше предела, — снимок вывески, сохранённый в PNG.
 */
export const MAX_LOGO_BYTES = 2 * 1024 * 1024

/**
 * 400 px по ДЛИННОЙ стороне.
 *
 * Цифра снята с библиотеки, а не выбрана на глаз: в 34 разборах логотипу отведено 11 гнёзд
 * шириной 0,168…0,402 доли кадра, а самый крупный профиль площадки — 1792 px по ширине.
 * Значит гнездо занимает 300…720 px, и 400 px покрывают типичное без растягивания.
 *
 * Длинная сторона, а не каждая: знак-надпись бывает 900×110, и требование «400 по обеим»
 * отвергло бы совершенно годный файл.
 */
export const MIN_LOGO_LONG_SIDE = 400

/** Как требования называются человеку — в подписи под полем загрузки. */
export const LOGO_HUMAN = 'PNG с прозрачным фоном, от 400 px по длинной стороне, до 2 МБ'

/**
 * Отказ по размеру файла — до чтения его содержимого.
 *
 * Отдельно от `rejectLogo`, чтобы браузер не втягивал в память стомегабайтный файл ради
 * ответа «слишком большой». `rejectLogo` эту же проверку делает первой: вызывающий,
 * знающий только про неё, ничего не пропускает.
 */
export function rejectLogoSize(size: number): string | null {
  if (size <= MAX_LOGO_BYTES) return null

  // Округление ВВЕРХ по той же причине, что и у фото: «2 МБ больше предела в 2 МБ» —
  // отказ, который нечего исправить.
  const megabytes = Math.ceil((size / 1024 / 1024) * 10) / 10
  return `${megabytes} МБ, это больше предела в 2 МБ`
}

/** Почему файл не годится в логотип — текстом для человека. `null` — файл принят. */
export function rejectLogo(bytes: Uint8Array): string | null {
  const tooBig = rejectLogoSize(bytes.length)
  if (tooBig !== null) return tooBig

  const info = readImageInfo(bytes)

  if (info === null || info.format !== 'png') {
    return 'нужен PNG: другие форматы не хранят прозрачность, и знак ляжет на карточку прямоугольником'
  }

  if (!hasTransparency(bytes)) {
    return 'у знака непрозрачный фон — на карточке он станет белым прямоугольником. Сохраните PNG с прозрачностью'
  }

  const longSide = Math.max(info.width, info.height)
  if (longSide < MIN_LOGO_LONG_SIDE) {
    return `${info.width}×${info.height} px — мелко для карточки. Нужно от ${MIN_LOGO_LONG_SIDE} px по длинной стороне`
  }

  return null
}

/**
 * Умеет ли PNG быть прозрачным.
 *
 * Тип цвета лежит в IHDR фиксированным смещением (подпись 8 + заголовок чанка 8 + ширина 4
 * + высота 4 + глубина 1). Значения 4 и 6 — это серый с альфой и RGBA. У остальных
 * прозрачность возможна только чанком `tRNS`, и его приходится искать проходом по чанкам.
 */
function hasTransparency(bytes: Uint8Array): boolean {
  const colorType = bytes[25]
  if (colorType === 4 || colorType === 6) return true

  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
  let offset = 8

  // 12 байт — минимальный чанк: длина, тип и контрольная сумма без данных.
  while (offset + 12 <= bytes.length) {
    const type = String.fromCharCode(bytes[offset + 4], bytes[offset + 5], bytes[offset + 6], bytes[offset + 7])
    if (type === 'tRNS') return true

    // По спецификации `tRNS` обязан стоять до пиксельных данных: дальше искать нечего, а
    // идти сквозь мегабайт IDAT ради заведомого «нет» незачем.
    if (type === 'IDAT') return false

    offset += 12 + view.getUint32(offset)
  }

  return false
}
