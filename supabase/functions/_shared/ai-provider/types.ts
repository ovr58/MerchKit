/**
 * Контракт модуля `ai-provider` (docs/SPEC.md §3, [ADR-0005](../../../../docs/adr/0005-ai-provider-abstraction.md)).
 *
 * **Вендор не выбран, и код о нём не знает.** Здесь описано только то, что нужно продукту:
 * пять независимых операций. Ни базового URL, ни имён моделей, ни формата запроса в этих
 * типах нет и быть не должно — они приезжают профилем провайдера из конфигурации, чтобы на
 * M5 менялся профиль, а не файлы.
 *
 * Операции независимы намеренно: «получилось изображение, но не получились тексты карточки»
 * — реальный исход, и веха обязана его отработать полным возвратом (US-E4). Слепи мы их в
 * один вызов, этот случай стал бы неотличим от полного отказа и необрабатываемым.
 *
 * **`moderate` — правка контракта шага 0 вехи M5, а не вход в её первоначальный состав.**
 * Добавлена решением пользователя 2026-08-29: модерация встаёт перед списанием в
 * `generate`, а туда приходят фото из готовой заявки, а не из шага мастера, где вызывается
 * `recognize` — набор к этому моменту мог измениться. Отдельная операция — единственный
 * способ проверить именно тот набор фото, что списывается и уходит в генерацию.
 */

import type { GenerationKind } from '../pricing.ts'

/**
 * Параметры конечного изображения для пары «маркетплейс × категория» (FR-25, ТЗ §5.2).
 *
 * Уходит **в запрос** к провайдеру, а не применяется после него: фон рисуется вместе с
 * кадром, а не подкладывается постобработкой (решение шага 0 вехи M4).
 */
export type OutputProfile = {
  marketplaceId: string
  marketplaceTitle: string
  categoryId: string
  /** Целевой кадр: что запрашиваем у провайдера и показываем пользователю до списания. */
  width: number
  height: number
  /** Порог площадки. Ниже — файл не примут; это и есть настоящее требование FR-25, тогда
   *  как целевой кадр выбираем мы под возможности вендора (миграция 20260829140000). */
  minWidth: number
  minHeight: number
  /** Соотношение сторон, которого требует площадка. Хранится отдельно от пикселей и НЕ
   *  выводится из них: целевой кадр под бакет вендора (1792 × 2400) сокращается в 56 : 75,
   *  а площадке и вендору нужны ровные 3 : 4. */
  aspectW: number
  aspectH: number
  aspectLabel: string
  /** Форматы, которые площадка принимает. Множественное число — не запас на будущее:
   *  модели изображений выбирают формат сами и на одинаковых запросах отдают то JPEG,
   *  то PNG (проверено на живом вендоре 2026-08-29). */
  formats: string[]
  maxBytes: number
  colorSpace: string
  backgroundHex: string
  backgroundTitle: string
}

/** Что за товар и как его показать — всё, что мастер собрал за шесть шагов. */
export type ProductBrief = {
  title: string
  description: string
  categoryTitle: string
  /** Промпт выбранного сценария показа. NULL у категории «Прочее» (FR-08). */
  presetPrompt: string | null
  presetTitle: string | null
  /** Свободные пожелания (FR-09). Для «Прочего» — единственный способ задать сценарий. */
  wishes: string
}

export type GeneratedImage = {
  bytes: Uint8Array
  contentType: string
  width: number
  height: number
}

/** Результат распознавания. NULL в любом поле — штатный исход US-E2, а не ошибка. */
export type Recognized = {
  categoryId: string | null
  productTitle: string | null
}

export type CardTexts = {
  title: string
  description: string
}

/**
 * Вердикт модерации. `allowed: false` — штатный отказ до списания, не ошибка вызова:
 * различать их обязан вызывающий код (генерация не запускается — ни то, ни другое не
 * повод бросать исключение). `reason` — для наших логов; наружу пользователю не идёт
 * (правило модуля: устройство провайдера не выносится в интерфейс).
 */
export type Moderated = {
  allowed: boolean
  reason?: string
}

/**
 * Себестоимость и длительность одного вызова вендора (шаг 4 плана вехи M5, `docs/SPEC.md`
 * §8–§9). Не часть результата операции — фиксация факта вызова для сверки цены в баллах,
 * поэтому идёт побочным каналом (`onUsage` в `createProvider`), а не полем в `Recognized`,
 * `CardTexts` и прочих: смешивать домен ответа с бухгалтерией значило бы менять контракт
 * ради учёта, которого он не касается.
 *
 * `recognize` сюда намеренно не входит — см. миграцию `20260830000000_generation_costs.sql`.
 */
export type ProviderUsage = {
  operation: 'moderate' | 'generateImages' | 'composeCard' | 'nameGeneration'
  /** Профиль, который в самом деле обслужил вызов ("stub" | "aitunnel") — записывается
   *  реализацией, а не берётся вызывающим из конфигурации: смена вендора мимо кода не
   *  должна расходиться с тем, что легло в БД. */
  vendor: string
  costRub: number
  durationMs: number
}

export interface AiProvider {
  /** Отказ до списания баллов в `generate` (решение шага 0 вехи M5). Пустой список фото
   *  проходит тривиально — проверять нечего. */
  moderate(photos: Uint8Array[]): Promise<Moderated>

  /** FR-03, FR-04: категория и наименование по фото. Не смог — вернуть NULL (US-E2). */
  recognize(photos: Uint8Array[]): Promise<Recognized>

  /** FR-25: изображения строго по профилю — кадр, разрешение, формат и фон. */
  generateImages(input: {
    photos: Uint8Array[]
    product: ProductBrief
    profile: OutputProfile
    /** «Карточка» — это изображение С ВЁРСТКОЙ поверх фото (FR-07), а не то же самое фото. */
    kind: GenerationKind
    /** Готовые тексты карточки — ровно то, что нужно нарисовать в блоке. NULL у типа «фото».
     *  Передаются намеренно, чтобы модель изображений не сочиняла содержимое сама: на замере
     *  2026-08-30 сочинение давало выдуманные характеристики и подписи полей вместо текста
     *  (план `planning/archive/plans/card-text-block_2026-08-30.md`). Поэтому `composeCard`
     *  вызывается ДО `generateImages`, хотя операции по-прежнему независимы. */
    card: CardTexts | null
    objects: number
  }): Promise<GeneratedImage[]>

  /** FR-07: заголовок и описание карточки. Только для типа «карточка». */
  composeCard(input: { product: ProductBrief; profile: OutputProfile }): Promise<CardTexts>

  /** FR-16: название генерации для каталога — список из «Генерация №17» нечитаем. */
  nameGeneration(input: { product: ProductBrief }): Promise<string>
}

/**
 * Профиль провайдера — то, что отличает одного вендора от другого, вынесенное в
 * конфигурацию (docs/SPEC.md §5). В коде остаются только имена переменных окружения.
 */
export type ProviderProfile = {
  name: string
  baseUrl: string | null
  imageModel: string | null
  /** Модель, на которую уходит повтор при отказе основной **по содержанию** запроса
   *  (ADR-0011). Не задана — повтора нет, поведение прежнее. */
  imageModelFallback: string | null
  /** Размеры кадра, которые принимает модель изображений, через запятую (`1024x1024,…`).
   *  Пусто — модель принимает бакеты разрешения, а не пиксели. Живёт в конфигурации, а не в
   *  коде: имён моделей и их особенностей в коде нет (docs/SPEC.md §5). */
  imageSizes: string | null
  imageSizesFallback: string | null
  textModel: string | null
}
