// PreToolUse на файлах аналитики: реестр событий правится ПЕРЕД кодом, не после.
// Носитель этого правила — сам хук: он однажды уже нарушался мимо скила, потому что скил
// открывается по памяти, а не по событию.
process.stdin.resume();
process.stdin.on('data', () => {});
process.stdin.on('end', () => {
  process.stdout.write(
    JSON.stringify({
      systemMessage:
        'Файл аналитики: открой скил instrumenting-analytics. Правило проекта — нужного свойства ' +
        'нет, значит сперва строка в docs/ANALYTICS.md, потом код. Имя свойства сверь с CONTEXT.md: ' +
        'одно понятие — одно слово во всех носителях.',
    }),
  );
});
