// SessionStart и SubagentStart: подмешивает в контекст правила, у которых нет иного носителя.
// Субагент (`Agent`, исполнитель плана) — не сессия: SessionStart на нём не срабатывает, поэтому
// тот же скрипт стоит и под SubagentStart, а имя события в ответе берётся из входа хука.
// Почему node: любой инициализированный из шаблона репозиторий — Node/TS, node есть всегда.
// Почему .mjs, а не .js: расширение `.mjs` — сигнал ESM для Node независимо от поля "type" в
// package.json конкретного проекта, так что хук не зависит от того, как настроен модульный
// режим у репозитория, в который его поставили.
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { onContour } from './contour-own-worktree.js';

const here = dirname(fileURLToPath(import.meta.url));
const text = readFileSync(join(here, 'session-start.md'), 'utf8');

// Харнесс требует, чтобы `hookEventName` совпадал с событием, на котором хук вызван. Пустой или
// битый вход (ручной запуск) — SessionStart, как было до SubagentStart.
let eventName = 'SessionStart';
try {
  eventName = JSON.parse(readFileSync(0, 'utf8')).hook_event_name || eventName;
} catch {}

// Полоса доверия зависит от модели (ADR-0002), и канон сам признаёт: машинно это не проверяется,
// держится на самообъявлении сессии. Один случай всё же проверяется — сторонний
// ANTHROPIC_BASE_URL значит, что сессия идёт не по подписке и модель точно не Opus и не Fable. Предикат
// контура берётся из contour-own-worktree.js, который на том же признаке запрещает заводить
// ветку в основном каталоге: два определения «что такое контур» разошлись бы.
const contourNotice = onContour()
  ? '\n\n---\n\n# Страховочный контур обнаружен машинно\n\n' +
    `\`ANTHROPIC_BASE_URL=${process.env.ANTHROPIC_BASE_URL}\` — не api.anthropic.com. Сессия идёт ` +
    'не по подписке, модель не Opus и не Fable, значит полоса консервативная (ADR-0002, ADR-T0013): ветки ' +
    '`feature/<slug>` · `fix/<slug>` · `exp/<slug>`, self-approve запрещён, готовится ' +
    'review-handoff.\n\n' +
    '**Твои строки в таблице сессий плана — вне доверенной полосы.** Строка Opus, Fable или помеченная неделимой — ' +
    'не твоя, остановись. **Эффорт — не выше `high`.** Шаг написан под исполнителя ниже ' +
    'планировщика: решать в нём нечего. Тянет думать долго — это брак шага, а не повод думать ' +
    'дольше: остановись и доложи, чего в тексте шага нет. ' +
    '**Свой `git worktree`** — ветки в основном каталоге хук не даст ни завести, ни переключить.\n\n' +
    '**Модель и эффорт выбраны на старте — внутри сессии не меняй.** Смена перестраивает префикс ' +
    'запроса и сбрасывает кэш контекста, дальше сессия платит полную цену за всё накопленное. ' +
    'Задача кончилась — `/clear`, а не следующая задача в том же окне. Канон (`CLAUDE.md`, ' +
    '`AGENTS.md`) правится своей сессией, не попутно: он едет в начале каждого запроса.\n\n' +
    '**Картинки может не видеть твоя модель.** Маршрутизации изображений по моделям в Claude ' +
    'Code нет: понадобился скриншот, макет, диаграмма — спавни субагента на модели со зрением ' +
    '(`CLAUDE_CODE_SUBAGENT_MODEL`), он вернёт содержимое текстом. Не уверен, что твоя модель ' +
    'видит, — своим `Read` картинку не открывай: провайдер вернёт ошибку посреди задачи.\n'
  : '';

process.stdout.write(
  JSON.stringify({
    hookSpecificOutput: { hookEventName: eventName, additionalContext: text + contourNotice },
  }),
);
